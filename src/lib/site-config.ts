export type ShareImage = { url: string; width: number; height: number; alt: string };

/** Branded share card generated by app/opengraph-image.tsx. */
const defaultShareImage: ShareImage = { url: '/opengraph-image', width: 1200, height: 630, alt: 'BSB Global — study abroad guidance from Nepal' };

/** Per-page SEO metadata. Pages without their own `image` use the branded share card. */
export function buildPageMetadata(title: string, description: string, path = '/', options: { image?: ShareImage; type?: 'website' | 'article' } = {}): Metadata {
  const url = new URL(path, siteOrigin);
  const images = [options.image ?? defaultShareImage];
  return {
    title,
    description,
    alternates: isSiteVerified ? { canonical: url.pathname } : undefined,
    openGraph: {
      title: `${title} | BSB Global`,
      description,
      type: options.type ?? 'website',
      siteName: 'BSB Global',
      locale: 'en_GB',
      images,
      ...(isSiteVerified ? {url: url.href} : {})
    },
    twitter: { card: 'summary_large_image', title: `${title} | BSB Global`, description, images: images.map(image => image.url) },
    robots: isSiteVerified ? {index:true,follow:true} : {index:false,follow:false}
  };
}

/** Absolute URL for structured data, which must not use relative links. */
export const absoluteUrl = (path: string) => new URL(path, siteOrigin).href;

